<?php

namespace App\Http\Resources;

use App\Models\Patient;
use Illuminate\Http\Request;
use Illuminate\Http\Resources\Json\JsonResource;

/** @mixin Patient */
class PatientResource extends JsonResource
{
    /** @return array<string, mixed> */
    public function toArray(Request $request): array
    {
        return [
            'id' => $this->id,
            'mrn' => $this->mrn,
            'facility_id' => $this->facility_id,
            'primary_provider_id' => $this->primary_provider_id,
            'referring_provider_id' => $this->referring_provider_id,
            'title' => $this->title,
            'first_name' => $this->first_name,
            'middle_name' => $this->middle_name,
            'last_name' => $this->last_name,
            'full_name' => $this->full_name,
            'date_of_birth' => $this->date_of_birth?->toDateString(),
            'sex' => $this->sex,
            'marital_status' => $this->marital_status,
            'nationality' => $this->nationality,
            'religion' => $this->religion,
            'language' => $this->language,
            'race' => $this->race,
            'ethnicity' => $this->ethnicity,
            'occupation' => $this->occupation,
            'national_id' => $this->national_id,
            'passport_number' => $this->passport_number,
            'drivers_license' => $this->drivers_license,
            'phone_cell' => $this->phone_cell,
            'phone_home' => $this->phone_home,
            'phone_work' => $this->phone_work,
            'email' => $this->email,
            'street' => $this->street,
            'city' => $this->city,
            'state' => $this->state,
            'postal_code' => $this->postal_code,
            'country_code' => $this->country_code,
            'registration_date' => $this->registration_date?->toDateString(),
            'registration_type' => $this->registration_type,
            'referral_source' => $this->referral_source,
            'price_level' => $this->price_level,
            'billing_note' => $this->billing_note,
            'clinical_alert' => $this->clinical_alert,
            'deceased_at' => $this->deceased_at?->toIso8601String(),
            'deceased_reason' => $this->deceased_reason,
            'facility' => $this->whenLoaded('facility', fn () => $this->facility ? [
                'id' => $this->facility->id,
                'name' => $this->facility->name,
                'code' => $this->facility->code,
            ] : null),
            'primary_provider' => $this->whenLoaded('primaryProvider', fn () => $this->primaryProvider ? [
                'id' => $this->primaryProvider->id,
                'full_name' => $this->primaryProvider->full_name,
            ] : null),
            'contacts' => $this->whenLoaded('contacts', fn () => $this->contacts->map(fn ($c) => [
                'id' => $c->id,
                'contact_type' => $c->contact_type,
                'relationship' => $c->relationship,
                'full_name' => $c->full_name,
                'sex' => $c->sex,
                'phone' => $c->phone,
                'email' => $c->email,
                'address' => $c->address,
                'country' => $c->country,
                'is_primary' => $c->is_primary,
            ])->values()->all()),
            'consent' => $this->whenLoaded('consent', fn () => $this->consent ? [
                'allow_sms' => $this->consent->allow_sms,
                'allow_email' => $this->consent->allow_email,
                'allow_voice' => $this->consent->allow_voice,
                'allow_mail' => $this->consent->allow_mail,
                'hipaa_notice_received' => $this->consent->hipaa_notice_received,
                'hipaa_message' => $this->consent->hipaa_message,
                'allow_immunization_registry' => $this->consent->allow_immunization_registry,
                'allow_health_info_exchange' => $this->consent->allow_health_info_exchange,
                'advance_directive_completed' => $this->consent->advance_directive_completed,
                'advance_directive_reviewed_at' => $this->consent->advance_directive_reviewed_at?->toDateString(),
            ] : null),
            'employers' => $this->whenLoaded('employers', fn () => $this->employers->map(fn ($e) => [
                'id' => $e->id,
                'employer_name' => $e->employer_name,
                'occupation' => $e->occupation,
                'department' => $e->department,
                'employment_status' => $e->employment_status,
                'phone' => $e->phone,
                'street' => $e->street,
                'city' => $e->city,
                'state' => $e->state,
                'postal_code' => $e->postal_code,
                'country' => $e->country,
                'is_current' => $e->is_current,
            ])->values()->all()),
            'insurances' => $this->whenLoaded('insurances', fn () => $this->insurances->map(fn ($i) => [
                'id' => $i->id,
                'tier' => $i->tier,
                'provider_name' => $i->provider_name,
                'plan_name' => $i->plan_name,
                'policy_number' => $i->policy_number,
                'group_number' => $i->group_number,
                'policy_type' => $i->policy_type,
                'subscriber_first_name' => $i->subscriber_first_name,
                'subscriber_middle_name' => $i->subscriber_middle_name,
                'subscriber_last_name' => $i->subscriber_last_name,
                'subscriber_relationship' => $i->subscriber_relationship,
                'subscriber_dob' => $i->subscriber_dob?->toDateString(),
                'subscriber_sex' => $i->subscriber_sex,
                'subscriber_phone' => $i->subscriber_phone,
                'copay' => $i->copay,
                'maximum_bill' => $i->maximum_bill,
                'accept_assignment' => $i->accept_assignment,
                'effective_date' => $i->effective_date?->toDateString(),
                'expiration_date' => $i->expiration_date?->toDateString(),
                'is_active' => $i->is_active,
            ])->values()->all()),
            'issues' => $this->whenLoaded('issues', fn () => PatientIssueResource::collection($this->issues)),
            'history' => $this->whenLoaded('history', fn () => $this->history ? [
                'lifestyle' => $this->history->lifestyle,
                'family_history' => $this->history->family_history,
                'surgical_history' => $this->history->surgical_history,
                'preventive_exams' => $this->history->preventive_exams,
                'mental_health' => $this->history->mental_health,
                'additional_notes' => $this->history->additional_notes,
                'updated_at' => $this->history->updated_at?->toIso8601String(),
            ] : null),
            'created_at' => $this->created_at?->toIso8601String(),
            'updated_at' => $this->updated_at?->toIso8601String(),
            'deleted_at' => $this->deleted_at?->toIso8601String(),
        ];
    }
}
